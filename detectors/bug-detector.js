// Create a GitHub issue
async function createIssue(title, body, labels = ['bug', 'auto-detected']) {
  try {
    const { data } = await octokit.rest.issues.create({
      owner: config.repo.split('/')[0],
      repo: config.repo.split('/')[1],
      title,
      body,
      labels,
    });
    return data;
  } catch (error) {
    console.error('Error creating issue:', error.message);
    return null;
  }
}

// Main function to run all detectors
async function runDetectors() {
  console.log('Starting bug detection scan...');
  
  const allIssues = [];
  
  // Get enabled detectors
  const enabledDetectors = Object.entries(config.detectors)
    .filter(([_, config]) => config.enabled)
    .map(([name, config]) => ({
      name,
      ...config,
      ...detectorDefinitions[name]
    }));
  
  // Scan each path with each detector
  for (const scanPath of config.scanPaths) {
    for (const detector of enabledDetectors) {
      console.log(`Running detector: ${detector.name} on path: ${scanPath}`);
      
      const results = scanDirectory(scanPath, detector);
      
      for (const result of results) {
        const title = `Bug: ${result.detector} in ${result.filePath}`;
        const body = issueTemplate(result.detector, result.filePath, result.match);
        
        const issue = await createIssue(title, body, [result.severity, 'bug', 'auto-detected']);
        if (issue) {
          allIssues.push(issue);
          console.log(`Created issue #${issue.number}: ${title}`);
        }
      }
    }
  }
  
  console.log(`Scan complete. Created ${allIssues.length} issues.`);
  return allIssues;
}

